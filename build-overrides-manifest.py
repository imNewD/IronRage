#!/usr/bin/env python3
"""
Run this after adding/removing/renaming files in images/overrides/.
It scans that folder and writes manifest.json, mapping each unit ID
(the part of the filename before the first underscore, or the whole
name if there's no underscore) to the actual filename.

Usage:
    python3 build-overrides-manifest.py

Place this file next to index.html (so images/overrides/ is alongside it),
or edit OVERRIDES_DIR below if your layout differs.
"""
import json
import os

OVERRIDES_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "images", "overrides")

def main():
    if not os.path.isdir(OVERRIDES_DIR):
        os.makedirs(OVERRIDES_DIR, exist_ok=True)
        print(f"Created {OVERRIDES_DIR} (it was missing). Add your images there and re-run.")
        return

    manifest = {}
    skipped = []
    for filename in sorted(os.listdir(OVERRIDES_DIR)):
        if filename == "manifest.json" or filename.startswith("."):
            continue
        if not os.path.isfile(os.path.join(OVERRIDES_DIR, filename)):
            continue
        name_no_ext = os.path.splitext(filename)[0]
        unit_id = name_no_ext.split("_", 1)[0]
        if not unit_id.isdigit():
            skipped.append(filename)
            continue
        if unit_id in manifest:
            print(f"Warning: multiple files for ID {unit_id} ({manifest[unit_id]!r} and {filename!r}) — using {filename!r}")
        manifest[unit_id] = filename

    out_path = os.path.join(OVERRIDES_DIR, "manifest.json")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, sort_keys=True)

    # Also write manifest.js: a plain <script>-loadable file containing the same
    # data. index.html loads THIS one. Unlike fetch(), a <script src="..."> tag
    # works fine when the page is opened directly by double-clicking (file://),
    # no local server required.
    js_path = os.path.join(OVERRIDES_DIR, "manifest.js")
    with open(js_path, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by build-overrides-manifest.py. Do not edit by hand.\n")
        f.write("window.OVERRIDE_MANIFEST = ")
        json.dump(manifest, f, indent=2, sort_keys=True)
        f.write(";\n")

    print(f"Wrote {out_path} and {js_path} with {len(manifest)} entr{'y' if len(manifest) == 1 else 'ies'}.")
    if skipped:
        print("Skipped (filename doesn't start with a numeric ID):")
        for s in skipped:
            print(f"  - {s}")

if __name__ == "__main__":
    main()
